"""Checks the HTML that the Power Apps HTML text controls receive (use cases 3 and 4).
The markup is generated by prototypes/build_prototypes.py with the same logic as the Power Fx."""
import os, subprocess, sys, json
from playwright.sync_api import sync_playwright

BASE = os.environ.get("RB_BASE", "http://localhost:8765")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHOTS = os.path.join(ROOT, "tests", "screenshots")
subprocess.run([sys.executable, os.path.join(ROOT, "prototypes", "build_prototypes.py")], check=True, capture_output=True)

results = []
def check(tid, name, cond, detail=""):
    results.append((tid, name, bool(cond), detail))
    print(("PASS " if cond else "FAIL ") + tid + " " + name + ((" – " + detail) if detail and not cond else ""))

with sync_playwright() as p:
    b = p.chromium.launch()
    pg = b.new_page(viewport={"width": 900, "height": 900})
    dialogs = []
    pg.on("dialog", lambda d: (dialogs.append(d.message), d.dismiss()))

    # H1 recipe card content and scaling
    pg.goto(BASE + "/prototypes/recipe-card.html")
    txt = pg.inner_text("body")
    check("H1", "Title with & shows correctly", "Herb & Cheese Skillet Eggs" in txt and "&amp;" not in txt)
    lis = pg.locator("ul li").all_inner_texts()
    check("H1", "Ingredients scaled to 4 servings", lis[:2] == ["8 eggs", "1/2 cup grated cheese"] and lis[4] == "salt and pepper", str(lis))
    check("H1", "Steps are numbered by the list, 4 of them", pg.locator("ol li").count() == 4)
    check("H1", "Allergen notice shown", "Contains (AI-suggested" in txt)
    pg.screenshot(path=os.path.join(SHOTS, "card_light.png"), full_page=True)
    pdf = pg.pdf(format="Letter")
    pages = pdf.count(b"/Type /Page") - pdf.count(b"/Type /Pages")
    check("H1", "Card prints on one Letter page", pages == 1, f"pages={pages}")

    # H2 hostile text is escaped
    pg.goto(BASE + "/prototypes/recipe-card-hostile.html")
    n_bad = pg.locator("script, img, b").count()
    t = pg.inner_text("body")
    check("H2", "No tags from recipe text become real elements", n_bad == 0 and not dialogs, f"elements={n_bad}")
    check("H2", "The text is still shown to the reader", "<script>alert(1)</script>" in t and "Mac 'n' <b>Cheese</b>" in t)
    check("H2", "A non-https source is not shown", "javascript:" not in t)

    # H3 chart
    pg.goto(BASE + "/prototypes/integration-chart.html")
    totals = pg.locator("tr:first-child td > div:first-child").all_inner_texts()
    check("H3", "7 days with run totals", totals == ["2", "3", "2", "3", "0", "4", "2"], str(totals))
    heights = pg.evaluate("""[...document.querySelectorAll('tr:first-child td')].map(td =>
        [...td.querySelectorAll('div')].slice(1).reduce((s, d) => s + d.getBoundingClientRect().height, 0))""")
    check("H3", "Busiest day (4 runs) is the full 120 px", round(heights[5]) == 120, str(heights))
    check("H3", "Bars scale with the count (2 runs = 60 px)", round(heights[0]) == 60, str(heights))
    reds = pg.evaluate("[...document.querySelectorAll('div')].filter(d => getComputedStyle(d).backgroundColor === 'rgb(220, 38, 38)' && d.style.height).length")
    check("H3", "Failures shown in red on the day they happened", reds == 1, f"red bars={reds}")
    check("H3", "Day labels run from 7 Nov to 13 Nov", pg.locator("tr:nth-child(2) td").first.inner_text() == "Sat 7"
          and pg.locator("tr:nth-child(2) td").last.inner_text() == "Fri 13")
    pg.screenshot(path=os.path.join(SHOTS, "chart_light.png"), full_page=True)
    pg.goto(BASE + "/prototypes/integration-chart-empty.html")
    check("H3", "No runs: 7 flat lines, no errors", pg.locator("tr:first-child td").count() == 7 and pg.inner_text("tr:first-child") .count("0") == 7)

    # H4 dark versions and phone width
    for f in ["recipe-card-dark", "integration-chart-dark"]:
        pg.goto(BASE + f"/prototypes/{f}.html")
        pg.screenshot(path=os.path.join(SHOTS, f.replace("recipe-", "").replace("integration-", "") + ".png"), full_page=True)
    m = b.new_page(viewport={"width": 390, "height": 844})
    m.goto(BASE + "/prototypes/recipe-card.html")
    sw = m.evaluate("document.documentElement.scrollWidth")
    check("H4", "Card fits a 390 px phone screen", sw <= 390, f"scrollWidth={sw}")
    m.screenshot(path=os.path.join(SHOTS, "card_phone.png"), full_page=True)
    b.close()

failed = [r for r in results if not r[2]]
print(f"\n{len(results) - len(failed)}/{len(results)} checks passed")
with open(os.path.join(ROOT, "tests", "e2e_html_controls_results.json"), "w") as f:
    json.dump([{"id": a, "check": c1, "pass": c2, "detail": d} for a, c1, c2, d in results], f, indent=1)
sys.exit(1 if failed else 0)
